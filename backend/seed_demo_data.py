def snap_to_route(bus_id, preferred_idx=None):
    """Return (lat, lng, name) for the exact waypoint at preferred_idx (or random spread)."""
    pts = ROUTE_COORDS[bus_id]
    if preferred_idx is not None:
        idx = preferred_idx % len(pts)
    else:
        idx = 0
    return pts[idx][0], pts[idx][1], pts[idx][2]


